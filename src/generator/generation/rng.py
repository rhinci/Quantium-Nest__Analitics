"""Независимые воспроизводимые потоки случайных чисел.

Каждая часть генератора (клиенты, заказы, аномалии) получает собственный
поток. Благодаря этому изменение числа вызовов в одной части не сдвигает
случайные последовательности в остальных.
"""

import random


def make_rng(seed: int, stream: str) -> random.Random:
    """Создаёт генератор для именованного потока.

    Одинаковые (seed, stream) всегда дают одинаковую последовательность.
    """
    return random.Random(f"{seed}:{stream}")
