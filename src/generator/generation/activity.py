"""Профиль активности магазина: время суток и день недели.

Все функции чистые: результат зависит только от переданного момента времени.
Множитель 1.0 означает «средняя интенсивность за сутки в обычный будний день»
(Пн–Чт), 2.0 — вдвое выше средней, 0.02 — почти полное затишье.
"""

from datetime import datetime

# Интенсивность на начало каждого часа (индекс = час суток) в условных единицах.
# Пики: 10:00–12:00 и 19:00–23:00. Ночью (2:00–7:00) активность почти нулевая.
_RAW_HOURLY: tuple[float, ...] = (
    0.70,  # 00
    0.20,  # 01
    0.03,  # 02
    0.02,  # 03
    0.02,  # 04
    0.02,  # 05
    0.03,  # 06
    0.05,  # 07
    0.80,  # 08
    1.30,  # 09
    2.20,  # 10
    2.30,  # 11
    2.10,  # 12
    1.40,  # 13
    1.10,  # 14
    1.00,  # 15
    1.10,  # 16
    1.20,  # 17
    1.60,  # 18
    2.20,  # 19
    2.50,  # 20
    2.50,  # 21
    2.40,  # 22
    1.90,  # 23
)

# Нормировка: делим на среднее, чтобы среднесуточный множитель был ровно 1.0.
_MEAN: float = sum(_RAW_HOURLY) / len(_RAW_HOURLY)
_HOURLY: tuple[float, ...] = tuple(value / _MEAN for value in _RAW_HOURLY)

# Множитель по дню недели: datetime.weekday() -> 0 = понедельник ... 6 = воскресенье.
# Пт, Сб, Вс — выше будничного уровня.
_WEEKDAY: tuple[float, ...] = (
    1.00,  # Пн
    1.00,  # Вт
    1.00,  # Ср
    1.00,  # Чт
    1.25,  # Пт
    1.40,  # Сб
    1.30,  # Вс
)


def hourly_factor(at: datetime) -> float:
    """Множитель по времени суток с плавным переходом между часами."""
    fraction = (at.minute * 60 + at.second + at.microsecond / 1_000_000) / 3600
    current = _HOURLY[at.hour]
    following = _HOURLY[(at.hour + 1) % 24]
    return current * (1.0 - fraction) + following * fraction


def weekday_factor(at: datetime) -> float:
    """Множитель по дню недели."""
    return _WEEKDAY[at.weekday()]


def activity_factor(at: datetime) -> float:
    """Итоговый множитель активности: время суток × день недели."""
    return hourly_factor(at) * weekday_factor(at)
